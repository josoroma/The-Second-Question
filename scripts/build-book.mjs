// Builds the files that are derived from the manuscript:
//   book/README.md, book/es/README.md   the table of contents for readers on GitHub
//   book/BOOK.md, book/es/BOOK.md       every page joined in reading order (no retyping)
//   art/readme/*.svg   light and dark copies of the logo and cover for README.md
//
// Reading order: front matter (00a- to 00z-), then each part's chapters
// (NN-slug.md) and closing page (NNm-with-a-machine-in-the-room.md), then
// back matter (90- to 99-).
//
// Usage: node scripts/build-book.mjs

import fs from "node:fs"
import path from "node:path"

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const site = "https://josoroma.github.io/The-Second-Question/"

const editions = [
  {
    toc: "src/data/toc.json",
    dir: "book",
    title: "The Second Question",
    subtitle:
      "How Builders Think Clearly, Speak Precisely, and Stay Human When Machines Write the First Draft",
    intro: `Read it online at [josoroma.github.io/The-Second-Question](${site}), or chapter by chapter below. [\`BOOK.md\`](BOOK.md) holds everything in one file. [En español](es/README.md).`,
    front: "Before you start",
    back: "At the back",
    part: "Part",
    closing: "Closing page",
  },
  {
    toc: "src/data/toc.es.json",
    dir: "book/es",
    title: "La segunda pregunta",
    subtitle:
      "Cómo quienes construyen piensan con claridad, hablan con precisión y siguen siendo humanos cuando las máquinas escriben el primer borrador",
    intro: `Léalo en línea en [josoroma.github.io/The-Second-Question/es](${site}es/), o capítulo por capítulo aquí abajo. [\`BOOK.md\`](BOOK.md) tiene todo en un solo archivo. [In English](../README.md).`,
    front: "Antes de empezar",
    back: "Al final del libro",
    part: "Parte",
    closing: "Página de cierre",
  },
]

for (const ed of editions) {
  const toc = JSON.parse(fs.readFileSync(path.join(root, ed.toc), "utf8"))
  const bookDir = path.join(root, ed.dir)
  const exists = (slug) => fs.existsSync(path.join(bookDir, `${slug}.md`))
  const read = (slug) => fs.readFileSync(path.join(bookDir, `${slug}.md`), "utf8").trim()
  const titleOf = (slug) => read(slug).match(/^#\s+(.+)$/m)?.[1]?.trim() ?? slug
  const matter = (pattern) =>
    fs
      .readdirSync(bookDir)
      .filter((file) => pattern.test(file))
      .sort()
      .map((file) => file.replace(/\.md$/, ""))
  const front = matter(/^00[a-z]-.+\.md$/)
  const back = matter(/^9\d-.+\.md$/)

  // README.md: the table of contents
  const lines = [`# ${ed.title}`, "", `*${ed.subtitle}*`, "", ed.intro, ""]
  if (front.length) {
    lines.push(`## ${ed.front}`, "")
    for (const slug of front) lines.push(`- [${titleOf(slug)}](${slug}.md)`)
    lines.push("")
  }
  for (const part of toc.parts) {
    lines.push(`## ${ed.part} ${part.number}. ${part.title}`, "", part.blurb, "")
    for (const chapter of part.chapters) {
      lines.push(
        exists(chapter.slug)
          ? `${chapter.number}. [${chapter.title}](${chapter.slug}.md)`
          : `${chapter.number}. ${chapter.title}`
      )
    }
    lines.push("")
    if (part.machine) {
      lines.push(
        exists(part.machine.slug)
          ? `${ed.closing}: *[${part.machine.title}](${part.machine.slug}.md)*`
          : `${ed.closing}: *${part.machine.title}*`,
        ""
      )
    }
  }
  if (back.length) {
    lines.push(`## ${ed.back}`, "")
    for (const slug of back) lines.push(`- [${titleOf(slug)}](${slug}.md)`)
    lines.push("")
  }
  fs.writeFileSync(path.join(bookDir, "README.md"), lines.join("\n"))

  // BOOK.md: front matter, each part's finished pages in order, back matter.
  const pieces = front.map(read)
  for (const part of toc.parts) {
    const slugs = [...part.chapters.map((chapter) => chapter.slug), ...(part.machine ? [part.machine.slug] : [])]
    const ready = slugs.filter(exists)
    if (!ready.length) continue
    pieces.push(`# ${ed.part} ${part.number}. ${part.title}`)
    for (const slug of ready) pieces.push(read(slug))
  }
  pieces.push(...back.map(read))
  fs.writeFileSync(
    path.join(bookDir, "BOOK.md"),
    `<!-- Generated by scripts/build-book.mjs from the chapter files. Do not edit by hand. -->\n\n${pieces.join("\n\n---\n\n")}\n`
  )
  const finished = toc.parts.flatMap((part) => part.chapters).filter((chapter) => exists(chapter.slug))
  console.log(`${ed.dir}/README.md and ${ed.dir}/BOOK.md written: ${finished.length} chapters.`)
}

// art/readme: GitHub shows SVGs as images, where currentColor has no page
// color to inherit, so write fixed-ink copies for light and dark themes.
const readmeDir = path.join(root, "art/readme")
fs.mkdirSync(readmeDir, { recursive: true })
const variants = [
  ["src/assets/brand/the-second-question-logo.svg", "logo"],
  ["src/assets/art/cover.svg", "cover"],
]
for (const [source, name] of variants) {
  const file = path.join(root, source)
  if (!fs.existsSync(file)) continue
  const svg = fs.readFileSync(file, "utf8")
  for (const [theme, ink] of [
    ["light", "#171717"],
    ["dark", "#ededed"],
  ]) {
    fs.writeFileSync(path.join(readmeDir, `${name}-${theme}.svg`), svg.replaceAll("currentColor", ink))
  }
}
